// ---------------------------------------------------------------------------
// Parse a level definition into a usable world description.
export function parseLevel(lvl) {
  const rows = lvl.rows;
  const numRows = rows.length;
  let cols = 0;
  for (const row of rows) cols = Math.max(cols, row.length);

  const grid = [];
  const enemies = [];
  const coins = [];
  let spawn = { x: 2 * TILE, y: 2 * TILE };
  let checkpoint = null;
  let flagX = null;
  let castleX = null;
  let castleY = null;

  for (let rIdx = 0; rIdx < numRows; rIdx++) {
    const row = rows[rIdx];
    const gridRow = new Array(cols).fill(null);
    for (let cIdx = 0; cIdx < cols; cIdx++) {
      const ch = row[cIdx] || ' ';
      if (ch === ' ') continue;

      if (ENTITY_CHARS.has(ch)) {
        const px = cIdx * TILE;
        const py = rIdx * TILE;
        if (ch === '@') {
          spawn = { x: px, y: py };
        } else if (ch === 'g') {
          enemies.push({ type: 'goomba', x: px, y: py });
        } else if (ch === 'k') {
          enemies.push({ type: 'koopa', x: px, y: py });
        } else if (ch === 'o') {
          coins.push({ x: px + TILE / 2, y: py + TILE / 2 });
        } else if (ch === 'v') {
          enemies.push({ type: 'flyer', x: px, y: py });
        } else if (ch === 'z') {
          enemies.push({ type: 'dasher', x: px, y: py });
        } else if (ch === 'p') {
          enemies.push({ type: 'piranha', x: px, y: py });
        } else if (ch === 'a') {
          enemies.push({ type: 'spiked', x: px, y: py });
        } else if (ch === 'm') {
          enemies.push({ type: 'flamer', x: px, y: py });
        } else if (ch === 'W') {
          enemies.push({ type: 'bowser', x: px, y: py });
        } else if (ch === 'c') {
          checkpoint = { x: px, y: py };
        }
        continue;
      }

      const type = TILES[ch];
      if (!type) continue;
      gridRow[cIdx] = type;
      if (type === 'flag' && flagX == null) flagX = cIdx * TILE;
      if (type === 'castle') { castleX = cIdx * TILE; castleY = rIdx * TILE; }
    }
    grid.push(gridRow);
  }

  // Optional checkpoint authored by a column index near a ground row.
  if (!checkpoint && lvl.checkpointCol != null) {
    // place the checkpoint flag at the first solid surface in that column
    const col = lvl.checkpointCol;
    let surfRow = numRows - 1;
    for (let rIdx = 0; rIdx < numRows; rIdx++) {
      if (grid[rIdx] && grid[rIdx][col]) { surfRow = rIdx; break; }
    }
    checkpoint = { x: col * TILE, y: (surfRow - 2) * TILE };
  }

  // Build moving platforms (positions are in tile units in the level def).
  const movers = (lvl.platforms || []).map((p) => ({
    x: p.x * TILE,
    y: p.y * TILE,
    axis: p.axis,
    range: p.range * TILE,
    speed: p.speed,
  }));

  return {
    grid,
    cols,
    rows: numRows,
    theme: lvl.theme,
    spawn,
    checkpoint,
    flagX,
    castleX,
    castleY,
    enemies,
    coins,
    movers,
    width: cols * TILE,
    height: numRows * TILE,
    time: lvl.time,
    name: lvl.name,
    id: lvl.id,
  };
}
